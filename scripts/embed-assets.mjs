// Bundles public/ into the Worker for environments where the static-asset
// upload API cannot be used (e.g. behind a credential-injecting proxy).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, extname, relative } from "node:path";

const TEXT = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".webmanifest": "application/manifest+json",
};
const BINARY = { ".png": "image/png", ".ico": "image/x-icon" };
const root = "public";
const out = {};
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      walk(full);
      continue;
    }
    const ext = extname(name);
    const key = `/${relative(root, full).split("\\").join("/")}`;
    if (TEXT[ext]) out[key] = { type: TEXT[ext], body: readFileSync(full, "utf8") };
    else if (BINARY[ext]) out[key] = { type: BINARY[ext], body: readFileSync(full).toString("base64"), base64: true };
  }
}
walk(root);
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/assets.ts",
  `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const EMBEDDED_ASSETS: Record<string, { type: string; body: string; base64?: boolean }> = ${JSON.stringify(out)};\n`
);
console.log(`Embedded ${Object.keys(out).length} files`);
