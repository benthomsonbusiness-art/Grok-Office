// Bundles public/ into the Worker for environments where the static-asset
// upload API cannot be used (e.g. behind a credential-injecting proxy).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, extname } from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
};
const root = "public";
const out = {};
for (const name of readdirSync(root)) {
  const full = join(root, name);
  if (!statSync(full).isFile()) continue;
  const type = TYPES[extname(name)];
  if (!type) continue;
  out[`/${name}`] = { type, body: readFileSync(full, "utf8") };
}
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/assets.ts",
  `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const EMBEDDED_ASSETS: Record<string, { type: string; body: string }> = ${JSON.stringify(out)};\n`
);
console.log(`Embedded ${Object.keys(out).length} files`);
